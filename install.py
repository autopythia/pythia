#!/usr/bin/env python3
"""Install ``ipythia``, ``autopythia`` and ``apply_patch`` into PREFIX/bin
(default: ~/.local/bin).

Run ``python3 install.py -e`` from the top level of a checkout. It points the symlink
~/.pythia/lib/pythia-dev at the current directory and writes wrappers for
``pythia.interaction.cli`` (ipythia), ``pythia.interaction.auto`` (autopythia) and
``pythia.interaction.apply_patch`` (apply_patch, for models that run it as a shell
command instead of calling the tool).
Re-run it from another checkout to switch; the wrappers themselves do not change.
This replaces any autopythia wrapper previously installed by legacy_install.py.
An apply_patch that this script did not write is left alone.

On a Mac, ``--enable-experimental-ui-plugin`` also builds the UI plugin, the crate in
_pythia_ui/, with cargo, and installs it into ~/.pythia/plugin/, for ipythia's option
of the same name.

Only editable (-e) installs are supported for now.
"""

from argparse import ArgumentParser
import os
import shlex
import shutil
import subprocess
import sys
from typing import NoReturn, Optional

ENTRYPOINTS = {
    "ipythia": "pythia.interaction.cli",
    "autopythia": "pythia.interaction.auto",
    "apply_patch": "pythia.interaction.apply_patch",
}
# Commands whose name other tools may install too: a file there that this
# script did not write (GENERATED_MARKER) is left in place, and reported.
KEEP_FOREIGN = frozenset({"apply_patch"})
GENERATED_MARKER = "# Generated by pythia's `python3 install.py -e`."

UI_PLUGIN_OPTION = "--enable-experimental-ui-plugin"
UI_PLUGIN_CRATE = "_pythia_ui"
UI_PLUGIN_FILE = "libpythia_ui.dylib"
# The crate's config (_pythia_ui/.cargo/config.toml) picks the target, rust-lld and
# its stub SDK, so a Mac needs a rustup toolchain, but no Xcode or Apple SDK.
UI_PLUGIN_BUILD = ("cargo", "build", "--offline", "--release", "--lib")
UI_PLUGIN_BUILT = os.path.join("target", "aarch64-apple-darwin", "release", UI_PLUGIN_FILE)


def cyan(s: str) -> str:
    return f"\x1b[36m{s}\x1b[0m" if sys.stdout.isatty() else s


def fail(msg: str) -> NoReturn:
    print(f"install.py: error: {msg}", file=sys.stderr)
    raise SystemExit(1)


def wrapper_script(pythonpath: str, module: str) -> str:
    # Like -m, but omit the launch directory so it cannot shadow imports. Python
    # 3.11+ spells that -P, which also keeps `ps` listings like a manual -m launch;
    # the probe costs a few ms per launch. Older Pythons run equivalent -c code.
    fallback = (
        "import sys; "
        "sys.path[:] = [p for p in sys.path if p]; "
        f'import runpy; runpy.run_module("{module}", run_name="__main__", alter_sys=True)'
    )
    return (
        "#!/bin/sh\n"
        f"{GENERATED_MARKER} PYTHONPATH is a symlink to the\n"
        "# checkout; re-run the installer from another checkout to switch. This runs\n"
        f"# `python3 -m {module}` minus the launch directory on sys.path,\n"
        "# where files could shadow imports: via -P on Python 3.11+, else via -c code.\n"
        f"export PYTHONPATH={shlex.quote(pythonpath)}\n"
        "if python3 -E -S -P -c '' 2>/dev/null; then\n"
        f'    exec python3 -P -m {shlex.quote(module)} "$@"\n'
        "fi\n"
        f'exec python3 -c {shlex.quote(fallback)} "$@"\n'
    )


def _discard(path: str) -> None:
    if os.path.lexists(path):
        os.unlink(path)


def written_by_installer(path: str) -> bool:
    """Whether ``path`` is a wrapper that this script wrote (GENERATED_MARKER)."""
    if os.path.islink(path) or not os.path.isfile(path):
        return False
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return GENERATED_MARKER in f.read(4096)
    except OSError:
        return False


def point_symlink(link: str, target: str) -> Optional[str]:
    """Atomically point ``link`` at ``target``; return its previous target, if any."""
    previous = os.readlink(link) if os.path.islink(link) else None
    if previous != target:
        tmp = f"{link}.tmp-{os.getpid()}"
        _discard(tmp)
        os.symlink(target, tmp)
        try:
            os.replace(tmp, link)  # rename(2): the link is never missing
        except BaseException:
            _discard(tmp)
            raise
    return previous


def write_executable(path: str, content: str) -> None:
    tmp = f"{path}.tmp-{os.getpid()}"
    _discard(tmp)
    try:
        with open(tmp, "x", encoding="utf-8") as f:
            f.write(content)
        os.chmod(tmp, 0o755)
        os.replace(tmp, path)
    except BaseException:
        _discard(tmp)
        raise


def install_file(source: str, path: str) -> None:
    """Copy ``source`` to ``path`` by renaming a copy over it, never by writing into
    it: a process that loaded the old file, such as a running ipythia with the
    plugin, would crash if it changed under it."""
    tmp = f"{path}.tmp-{os.getpid()}"
    _discard(tmp)
    try:
        shutil.copyfile(source, tmp)
        os.chmod(tmp, 0o755)
        os.replace(tmp, path)
    except BaseException:
        _discard(tmp)
        raise


def build_ui_plugin(crate: str) -> str:
    """Build the UI plugin in ``crate`` (_pythia_ui/) and return the library's path.
    The build writes only into the crate's target/; a failure ends the install
    before anything changes."""
    print(f"Building the UI plugin in {cyan(crate)}: {shlex.join(UI_PLUGIN_BUILD)}", flush=True)
    try:
        result = subprocess.run(UI_PLUGIN_BUILD, cwd=crate)
    except FileNotFoundError:
        fail(f"{UI_PLUGIN_OPTION}: cargo is not on PATH; the plugin needs a rustup "
             "toolchain (https://rustup.rs), which has the rust-lld linker that "
             "Homebrew's Rust lacks. Nothing was installed.")
    if result.returncode != 0:
        fail(f"{UI_PLUGIN_OPTION}: building the UI plugin failed (cargo exited "
             f"{result.returncode}). Nothing was installed.")
    built = os.path.join(crate, UI_PLUGIN_BUILT)
    if not os.path.isfile(built):
        fail(f"{UI_PLUGIN_OPTION}: the build made no {built}. Nothing was installed.")
    return built


def main() -> None:
    parser = ArgumentParser(
        description=("Install ipythia, autopythia and apply_patch "
                     "(pythia.interaction.cli/auto/apply_patch) into PREFIX/bin."),
    )
    parser.add_argument(
        "-e", "--editable", action="store_true",
        help=("run the commands from the current checkout through the "
              "~/.pythia/lib/pythia-dev symlink (required for now)"),
    )
    parser.add_argument(
        "--prefix", default=None,
        help="install the commands into PREFIX/bin (default: ~/.local)",
    )
    parser.add_argument(
        UI_PLUGIN_OPTION, action="store_true",
        help=("macOS on Apple Silicon: also build the experimental UI plugin from "
              f"{UI_PLUGIN_CRATE}/ (cargo, from a rustup toolchain) and install it into "
              f"~/.pythia/plugin/, for ipythia's {UI_PLUGIN_OPTION}"),
    )
    args = parser.parse_args()
    if not args.editable:
        parser.error("only editable installs are supported for now; pass -e")

    home = os.path.expanduser("~")
    if args.prefix is not None:
        prefix = os.path.abspath(os.path.expanduser(args.prefix))
    else:
        prefix = os.path.join(home, ".local")
    bin_dir = os.path.join(prefix, "bin")
    destinations = {os.path.join(bin_dir, name): module for name, module in ENTRYPOINTS.items()}
    link = os.path.join(home, ".pythia", "lib", "pythia-dev")
    plugin_dir = os.path.join(home, ".pythia", "plugin")
    plugin = os.path.join(plugin_dir, UI_PLUGIN_FILE)
    cwd = os.getcwd()

    # Check everything before changing anything.
    for module in ENTRYPOINTS.values():
        entry = os.path.join(cwd, *module.split(".")) + ".py"
        if not os.path.isfile(entry):
            fail(f"run this from the top level of a pythia checkout ({entry} not found)")
    if os.path.lexists(link) and not os.path.islink(link):
        fail(f"refusing to replace {link}: it exists and is not a symlink")
    # Left in place: a command of a shared name that another tool installed.
    foreign = [
        dst for dst in destinations
        if os.path.basename(dst) in KEEP_FOREIGN and os.path.lexists(dst)
        and not written_by_installer(dst)
    ]
    for dst in foreign:
        del destinations[dst]
    for dst in destinations:
        if os.path.lexists(dst) and not (os.path.islink(dst) or os.path.isfile(dst)):
            fail(f"refusing to replace {dst}: it is not a regular file or symlink")
    built = None
    if args.enable_experimental_ui_plugin:
        if sys.platform != "darwin":
            fail(f"{UI_PLUGIN_OPTION}: the UI plugin is for macOS on Apple Silicon, and this "
                 f"is {sys.platform}; its crate's Makefile cross-builds it ({UI_PLUGIN_CRATE}/)")
        crate = os.path.join(cwd, UI_PLUGIN_CRATE)
        if not os.path.isfile(os.path.join(crate, "Cargo.toml")):
            fail(f"{UI_PLUGIN_OPTION}: {crate}/Cargo.toml not found; run this from the top "
                 "level of a pythia checkout that has the UI plugin's crate")
        if os.path.lexists(plugin_dir) and not os.path.isdir(plugin_dir):
            fail(f"refusing to replace {plugin_dir}: it exists and is not a directory")
        if os.path.lexists(plugin) and not (os.path.islink(plugin) or os.path.isfile(plugin)):
            fail(f"refusing to replace {plugin}: it is not a regular file or symlink")
        built = build_ui_plugin(crate)  # the last check: it changes nothing here

    os.makedirs(os.path.dirname(link), exist_ok=True)
    previous = point_symlink(link, cwd)
    os.makedirs(bin_dir, exist_ok=True)
    for dst, module in destinations.items():
        write_executable(dst, wrapper_script(link, module))
    if built is not None:
        os.makedirs(plugin_dir, exist_ok=True)
        install_file(built, plugin)

    if previous is None:
        change = "new"
    elif previous == cwd:
        change = "unchanged"
    else:
        change = f"was {previous}"
    print(f"Current working dir = {cyan(cwd)}")
    print(f"Python path (dev)   = {cyan(link)} -> {cyan(cwd)} ({change})")
    for dst in destinations:
        print(f"Installed           = {cyan(dst)}")
    if built is not None:
        print(f"Installed           = {cyan(plugin)} (UI plugin; running sessions keep the one "
              "they loaded until they restart)")
    for dst in foreign:
        print(f"Left in place       = {cyan(dst)} (not written by install.py; "
              "remove it and re-run to install pythia's)")
    path_dirs = {os.path.normpath(p) for p in os.environ.get("PATH", "").split(os.pathsep) if p}
    if os.path.normpath(bin_dir) not in path_dirs:
        print(f"Note: {bin_dir} is not on PATH (a new login shell may add it).")
    print("Done installation.")


if __name__ == "__main__":
    main()
