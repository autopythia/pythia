#!/usr/bin/env python3
"""Add to stub-sdk/usr/lib/libSystem.tbd what binaries import.

`make tbd` links every binary with `-undefined dynamic_lookup`, so symbols
missing from the current stub still link (as flat-namespace lookups), then
runs this. The stub keeps the symbols that it lists, and gains every symbol
those binaries take from libSystem or leave unresolved, plus
dyld_stub_binder, which the linker itself refers to. So one stub serves each
Rust version that has run it, though their std imports differ: 1.78's uses
pthread_cond_timedwait and getentropy, where 1.93's uses
pthread_cond_timedwait_relative_np and CCRandomGenerateBytes. With
--replace, the stub lists only what these binaries import. Objective-C
runtime and framework symbols are refused: they belong in that library's
hand-written .tbd.

usage: gen_tbd.py [--replace] OUT.tbd BINARY...
"""

# From research-gui (_glomery/tools/gen_tbd.py, commit a5099c9), changed to
# keep what the stub lists (--replace does what the original did). Here
# `make tbd` passes the program, the plugin (a dylib) and the unit tests.

import os
import re
import sys

from macho_info import FLAT_LOOKUP_ORDINAL, MachO

INSTALL_NAME = "/usr/lib/libSystem.B.dylib"
CURRENT_VERSION = "1292.60.1"  # about the macOS 11 SDK's (the deployment target)
TBD_TARGETS = {"arm64": "arm64-macos"}
# Symbols that come from libobjc or a framework, not libSystem.
FOREIGN = re.compile(
    r"_(objc|class|object|sel|protocol|method|ivar|property|imp)_|__objc_|_OBJC_|_k?(NS|CF|CG)[A-Z]"
)


def listed(text):
    """The symbols that a stub in this script's format lists."""
    match = re.search(r"symbols:\s*\[(.*?)\]", text, re.S)
    return set(match.group(1).replace(",", " ").split()) if match else set()


def main(argv):
    replace = argv[:1] == ["--replace"]
    if replace:
        argv = argv[1:]
    if len(argv) < 2:
        sys.exit(__doc__.strip())
    out, paths = argv[0], argv[1:]
    archs, imported = set(), set()
    for path in paths:
        m = MachO(path)
        archs.add(m.arch)
        ordinals = {i + 1 for i, (name, _, _) in enumerate(m.dylibs) if name == INSTALL_NAME}
        ordinals.add(FLAT_LOOKUP_ORDINAL)
        imported.update(name for name, ordinal in m.imports() if ordinal in ordinals)
    if len(archs) != 1 or not archs <= TBD_TARGETS.keys():
        sys.exit(f"gen_tbd: expected only arm64 binaries, got {sorted(archs)}")
    old = None
    if os.path.exists(out):
        with open(out) as f:
            old = f.read()
    before = listed(old) if old is not None else set()
    symbols = imported | {"dyld_stub_binder"} | (set() if replace else before)
    foreign = sorted(s for s in symbols if FOREIGN.match(s))
    if foreign:
        sys.exit("gen_tbd: not libSystem symbols; add them to their library's .tbd:\n  " + "\n  ".join(foreign))
    target = TBD_TARGETS[archs.pop()]
    listing = ",\n".join(" " * 23 + symbol for symbol in sorted(symbols)).lstrip()
    text = f"""\
--- !tapi-tbd
# Generated by tools/gen_tbd.py (`make tbd`), which keeps what's listed and
# adds what this crate's binaries import from libSystem, so the stub serves
# each Rust version that ran it (names only; see README.md, "Stub SDK").
tbd-version:     4
targets:         [ {target} ]
install-name:    '{INSTALL_NAME}'
current-version: {CURRENT_VERSION}
exports:
  - targets:         [ {target} ]
    symbols:         [ {listing} ]
...
"""
    if text != old:  # an unchanged stub keeps its mtime, so nothing relinks
        with open(out, "w") as f:
            f.write(text)
    added, removed = sorted(symbols - before), sorted(before - symbols)
    change = (" (unchanged)" if text == old else
              "".join(f"\n  {sign} {name}" for sign, names in (("+", added), ("-", removed))
                      for name in names))
    print(f"gen_tbd: {out}: {len(symbols)} symbols{change}")


if __name__ == "__main__":
    main(sys.argv[1:])
