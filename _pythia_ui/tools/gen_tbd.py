#!/usr/bin/env python3
"""Rewrite stub-sdk/usr/lib/libSystem.tbd to list what binaries import.

`make tbd` links every binary with `-undefined dynamic_lookup`, so symbols
missing from the current stub still link (as flat-namespace lookups), then
runs this. The new stub lists every symbol those binaries take from
libSystem or leave unresolved, plus dyld_stub_binder, which the linker
itself refers to. Objective-C runtime and framework symbols are refused:
they belong in that library's hand-written .tbd.

usage: gen_tbd.py OUT.tbd BINARY...
"""

# From research-gui (_glomery/tools/gen_tbd.py, commit a5099c9), unchanged but
# for this comment: here `make tbd` passes the program, the plugin (a dylib) and
# the unit tests.

import os
import re
import sys

from macho_info import FLAT_LOOKUP_ORDINAL, MachO

INSTALL_NAME = "/usr/lib/libSystem.B.dylib"
CURRENT_VERSION = "1292.60.1"  # about the macOS 11 SDK's (the deployment target)
TBD_TARGETS = {"arm64": "arm64-macos"}
# Symbols that come from libobjc or a framework, not libSystem.
FOREIGN = re.compile(
    r"_(objc|class|object|sel|protocol|method|ivar|property|imp)_|__objc_|_OBJC_|_k?(NS|CF|CG)[A-Z]"
)


def main(argv):
    if len(argv) < 2:
        sys.exit(__doc__.strip())
    out, paths = argv[0], argv[1:]
    archs, symbols = set(), set()
    for path in paths:
        m = MachO(path)
        archs.add(m.arch)
        ordinals = {i + 1 for i, (name, _, _) in enumerate(m.dylibs) if name == INSTALL_NAME}
        ordinals.add(FLAT_LOOKUP_ORDINAL)
        symbols.update(name for name, ordinal in m.imports() if ordinal in ordinals)
    if len(archs) != 1 or not archs <= TBD_TARGETS.keys():
        sys.exit(f"gen_tbd: expected only arm64 binaries, got {sorted(archs)}")
    foreign = sorted(s for s in symbols if FOREIGN.match(s))
    if foreign:
        sys.exit("gen_tbd: not libSystem symbols; add them to their library's .tbd:\n  " + "\n  ".join(foreign))
    symbols.add("dyld_stub_binder")
    target = TBD_TARGETS[archs.pop()]
    listing = ",\n".join(" " * 23 + symbol for symbol in sorted(symbols)).lstrip()
    text = f"""\
--- !tapi-tbd
# Generated by tools/gen_tbd.py (`make tbd`); don't edit. The libSystem
# symbols this repo's binaries import (names only; see README.md, "Stub SDK").
tbd-version:     4
targets:         [ {target} ]
install-name:    '{INSTALL_NAME}'
current-version: {CURRENT_VERSION}
exports:
  - targets:         [ {target} ]
    symbols:         [ {listing} ]
...
"""
    old = None
    if os.path.exists(out):
        with open(out) as f:
            old = f.read()
    with open(out, "w") as f:
        f.write(text)
    print(f"gen_tbd: {out}: {len(symbols)} symbols{' (unchanged)' if text == old else ''}")


if __name__ == "__main__":
    main(sys.argv[1:])
